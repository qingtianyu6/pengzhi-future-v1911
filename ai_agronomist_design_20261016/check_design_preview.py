from pathlib import Path
from playwright.sync_api import sync_playwright,expect
BASE=Path(__file__).resolve().parent
checks=[]
with sync_playwright() as p:
 browser=p.chromium.launch()
 for width,height in [(1440,1000),(390,844)]:
  page=browser.new_page(viewport={'width':width,'height':height},reduced_motion='reduce')
  errors=[]
  requests=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  page.on('request',lambda r:requests.append(r.url) if r.url.startswith('http') else None)
  page.goto((BASE/'AI农艺师_交互概念预览.html').as_uri())
  def check(name):
   assert not errors,errors
   assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),(width,name)
   checks.append(str(width)+' '+name)
  expect(page.get_by_role('tab',name='生长档案',exact=True)).to_have_attribute('aria-selected','true')
  page.screenshot(path=str(BASE/('概念预览_生长档案_'+str(width)+'.png')))
  page.get_by_role('button',name='观察第1周 建立基线').click()
  expect(page.locator('#stage-title')).to_have_text('建立批次基线')
  page.get_by_role('button',name='观察第3周 提出研究问题').click()
  check('生长快照切换')
  for name,view in [('方案推演','scenarios'),('生产研究','research'),('农事技能','skills'),('目标编排','goals')]:
   page.get_by_role('tab',name=name,exact=True).click()
   expect(page.locator('#view-'+view)).to_be_visible()
   check(name+'视图')
  page.get_by_role('tab',name='方案推演',exact=True).click()
  page.get_by_label('观察范围',exact=True).select_option('7')
  page.get_by_role('button',name='选择 C',exact=True).click()
  page.get_by_role('button',name='加入目标草稿 →',exact=True).click()
  expect(page.locator('#goal-scenario')).to_have_text('方案 C · 未来7天')
  page.get_by_role('tab',name='方案推演',exact=True).click()
  page.get_by_role('button',name='选择 A',exact=True).click()
  page.get_by_role('tab',name='目标编排',exact=True).click()
  expect(page.locator('#goal-scenario')).to_have_text('方案 C · 未来7天')
  check('方案草稿保留所选快照')
  page.get_by_role('tab',name='生产研究',exact=True).click()
  page.locator('#research-question').fill('')
  page.get_by_role('button',name='预览研究草案 →',exact=True).click()
  expect(page.get_by_role('dialog')).to_contain_text('补充研究问题')
  page.get_by_role('button',name='关闭详情',exact=True).click()
  question='清晨重复高湿与管理记录之间有什么关系？'
  page.locator('#research-question').fill(question)
  page.get_by_role('button',name='预览研究草案 →',exact=True).click()
  expect(page.locator('#study-title')).to_have_text(question)
  page.screenshot(path=str(BASE/('概念预览_生产研究_'+str(width)+'.png')))
  check('研究草案与缺失输入')
  page.get_by_role('button',name='整理为待验证技能草稿',exact=True).click()
  expect(page.locator('.skill-card')).to_have_count(4)
  expect(page.locator('.skill-card').last).to_contain_text('未验证草稿')
  page.locator('[data-skill=data]').click()
  expect(page.get_by_role('dialog')).to_contain_text('人工编写的流程模板示例')
  page.get_by_role('button',name='关闭详情',exact=True).click()
  check('研究关联技能草稿')
  page.get_by_role('tab',name='目标编排',exact=True).click()
  expect(page.locator('#goal-study')).to_have_text('研究草案 · 观察未开展')
  expect(page.locator('#goal-skill')).to_have_text('环境数据中断核查模板')
  page.locator('#goal-input').fill('<img src=x onerror="window.previewInjected=true">')
  page.get_by_role('button',name='预览编排结果 →',exact=True).click()
  assert page.locator('#goal-title img').count()==0
  assert not page.evaluate('window.previewInjected===true')
  page.locator('#goal-input').fill('未来一周关注开花坐果期，安排巡棚、观察和复查。')
  page.get_by_role('button',name='预览编排结果 →',exact=True).click()
  page.get_by_role('button',name='查看计划关联',exact=True).click()
  expect(page.get_by_role('dialog')).to_contain_text('方案 C · 未来7天')
  expect(page.get_by_role('dialog')).to_contain_text('已生成草案')
  page.get_by_role('button',name='关闭详情',exact=True).click()
  page.get_by_role('button',name='预览确认流程',exact=True).click()
  expect(page.get_by_role('dialog')).to_contain_text('没有向现有平台提交数据')
  page.get_by_role('button',name='关闭详情',exact=True).click()
  check('目标编排与跨视图关联')
  page.screenshot(path=str(BASE/('概念预览_目标编排_'+str(width)+'.png')))
  page.reload()
  page.get_by_role('tab',name='农事技能',exact=True).click()
  expect(page.locator('.skill-card')).to_have_count(3)
  page.get_by_role('tab',name='农事技能',exact=True).press('ArrowRight')
  expect(page.get_by_role('tab',name='目标编排',exact=True)).to_have_attribute('aria-selected','true')
  expect(page.locator('#goal-scenario')).to_have_text('尚未加入')
  assert not requests,requests
  check('重置、键盘导航与无外部写入')
  page.close()
 browser.close()
(BASE/'概念稿检查记录.txt').write_text('\n'.join(checks),encoding='utf-8')
print('PASSED',len(checks),checks,flush=True)

