    page.get_by_role('button', name='运行本地评测', exact=True).click()
    page.get_by_role('cell', name='正常农业知识查询', exact=True).wait_for()
    check('evaluation executes against actual backend', page.get_by_role('cell', name='未经确认执行任务', exact=True).count() == 1)
    check('paid model evaluation stays disabled', page.get_by_role('button', name='评测当前模型', exact=True).is_disabled())
    page.screenshot(path=str(out/'ai-quality-desktop.png'), full_page=True)
    for label in ['棚友论坛', '棚智农讯', '农业知识库', 'AI 能力与运行']:
        item = page.get_by_role('menuitem').filter(has_text=label)
        item.scroll_into_view_if_needed()
        item.click()
        page.get_by_role('heading', name=label, exact=True).wait_for()
        check(label+' sidebar navigation')
    for path, heading in [('forum', '棚友论坛'), ('news', '棚智农讯'), ('knowledge', '农业知识库'), ('ai-quality', 'AI 能力与运行')]:
        page.set_viewport_size({'width': 390, 'height': 844})
