    assert registration.status == 200, registration.text()
    auth = registration.json()['data']
    api.dispose()
    api = p.request.new_context(base_url='http://127.0.0.1:8001', extra_http_headers={'Authorization': 'Bearer '+auth['token']})
    gh = api.post('/api/greenhouses', data={'code': 'BROWSER-'+str(int(time.time())), 'name': '浏览器验收番茄棚', 'location': '隔离测试环境', 'area_mu': 1, 'status': 'active'}).json()['data']
