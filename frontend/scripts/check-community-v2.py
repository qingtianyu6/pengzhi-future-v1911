    batch = api.post(f'/api/greenhouses/{gid}/crop-batches', data={'batch_code': 'BROWSER-BATCH-'+str(int(time.time())), 'variety': '测试番茄', 'crop_type': 'tomato', 'planted_at': (date.today()-timedelta(days=40)).isoformat(), 'status': 'growing'})
    assert batch.status == 201, batch.text()
    browser = p.chromium.launch()
    page = browser.new_page(viewport={'width': 1440, 'height': 1000}, reduced_motion='reduce')
    page.set_default_timeout(20000)
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.add_init_script('localStorage.setItem("pengzhi_auth_token", '+json.dumps(auth['token'])+'); localStorage.setItem("pengzhi_auth_user", '+json.dumps(json.dumps(auth['user'], ensure_ascii=False))+');')
    def visit(path):
        page.goto(f'http://127.0.0.1:5174/platform/{path}?greenhouse_id={gid}', wait_until='networkidle')
    visit('forum')
    page.get_by_role('button', name='发布帖子').click()
    dialog = page.get_by_role('dialog')
    dialog.get_by_label('帖子标题', exact=True).fill('番茄叶面观察：浏览器完整流程')
    dialog.get_by_label('正文（支持 Markdown）', exact=True).fill('记录了**作物阶段与观察区域**，需要比较处理前后叶面湿润比例。这是自动化验收内容。')
    dialog.get_by_role('button', name='确认发布', exact=True).click()
    page.get_by_role('heading', name='番茄叶面观察：浏览器完整流程').wait_for()
    check('formal forum post persists through real API')
    page.get_by_role('textbox', name='回复内容').fill('补充同一区域处理前后的数值记录，保留原始出处。')
    page.get_by_role('button', name='发表回复', exact=True).click()
    page.get_by_role('button', name='采纳答案', exact=True).click()
    page.get_by_text('已采纳', exact=True).wait_for()
    check('comment and accepted answer')
    page.get_by_role('button', name='收藏帖子', exact=True).click()
    page.get_by_role('button', name='取消收藏', exact=True).wait_for()
    page.get_by_role('button', name='取消收藏', exact=True).click()
    page.get_by_role('button', name='收藏帖子', exact=True).wait_for()
    check('bookmark add and remove')
    page.get_by_role('button', name=re.compile(r'^举\s*报$')).click()
    dialog = page.get_by_role('dialog')
    dialog.get_by_role('textbox', name='举报原因').fill('请求检查经验是否可以作为研究参考')
    dialog.get_by_role('button', name='确 定', exact=True).click()
    dialog.wait_for(state='hidden')
    page.get_by_role('button', name='审核经验', exact=True).click()
    page.get_by_text('经验已审核', exact=True).wait_for()
    check('report and administrator moderation')
    page.get_by_role('button', name='检索相关知识', exact=True).click()
    page.get_by_role('dialog').wait_for()
    page.get_by_role('dialog').get_by_role('button', name=re.compile(r'^关\s*闭$')).click()
    check('private evidence assistant does not publish comments')
    page.locator('.ant-modal-mask').wait_for(state='hidden')
    page.screenshot(path=str(out/'forum-desktop.png'), full_page=True)
    page.get_by_role('button', name='创建研究草稿', exact=True).click()
    page.wait_for_url('**/platform/research?**')
    page.get_by_role('heading', name='番茄叶面观察：浏览器完整流程').wait_for()
    check('forum creates a real study in existing research module')
    visit('knowledge')
    page.get_by_role('button', name='导入农业文档', exact=True).click()
    dialog = page.get_by_role('dialog')
    dialog.locator('input[type=file]').set_input_files({'name': 'browser-guide.md', 'mimeType': 'text/markdown', 'buffer': '# 番茄叶面湿润观察\n\n番茄叶面湿润比例需要在同一区域记录处理前后数据，同时保留观察时间、作物阶段及伴随操作。这是用于浏览器验收的测试文档，不是正式农艺指导。'.encode()})
    dialog.get_by_label('文档标题', exact=True).fill('浏览器验收观察文档')
    dialog.get_by_label('适用作物', exact=True).locator('xpath=../..').click()
    page.locator('.ant-select-dropdown:visible').get_by_text('番茄', exact=True).click()
    dialog.get_by_label('文档标题', exact=True).click()
    dialog.get_by_role('checkbox').check()
    dialog.get_by_role('button', name='导入并解析', exact=True).click()
    dialog.wait_for(state='hidden')
    page.get_by_role('button', name='审核为可信参考', exact=True).click()
    page.get_by_role('button', name='撤销可信标记', exact=True).wait_for()
    page.get_by_role('searchbox', name='农业知识问题').fill('番茄叶面湿润比例')
