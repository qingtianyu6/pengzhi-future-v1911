    guest.get_by_role('heading', name='游客隔离验收', exact=True).wait_for()
    check('guest post stays local with no community API writes', not writes)
    guest.reload(wait_until='networkidle')
    guest.get_by_role('heading', name='游客隔离验收', exact=True).wait_for()
    check('guest post persists in current browser session')
    check('guest has no JavaScript errors', not errors)
    guest.close()
    browser.close(); api.dispose()
